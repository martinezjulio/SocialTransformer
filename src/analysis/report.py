# %% report
"""The results document (meta-plan 9): every ``numbers.json`` merged with the provenance block, checked against the
manifest, and written as ``paper/results.tex`` (one ``\\newcommand`` per number, a composed ``…CI`` macro per
estimate/lo/hi triple) and ``paper/results.md`` (every macro, key and value by block, regenerated each run so a diff
shows what changed), and the booktabs tables ``paper/tables/{hypotheses,ladder}.tex`` from pandas. The stage that calls this is
registered in 9.5.
"""

import datetime
import hashlib
import json
import subprocess
from pathlib import Path

import pandas as pd

from analysis.data import checkpoint_path
from analysis.numbers import DEMOGRAPHICS, MANIFEST, check_manifest, fmt, kind_of, macro_name
from analysis.policies import REGISTRY

STAGES_WITH_NUMBERS = ("descriptive", "partner_choice", "choice", "checks", "unseen")


def provenance(preprocessed: Path, eval_dir: Path, n_participants: int, n_sessions: int, n_trials: int) -> dict:
    """Commit (``-dirty`` when the tree has changes), checkpoint sha256, run date, the sizes, the exclusion ledger and the
    demographics summary (both written beside the preprocessed file)."""
    git = lambda *a: subprocess.run(["git", *a], capture_output=True, text=True, cwd=Path(__file__).parent).stdout.strip()
    ckpt = checkpoint_path(eval_dir)
    ledger = pd.read_csv(Path(preprocessed).parent / "exclusions.csv")
    demographics = pd.read_csv(Path(preprocessed).parent / "demographics_summary.csv").set_index("name")["value"]
    return {"commit": git("rev-parse", "HEAD") + ("-dirty" if git("status", "--porcelain") else ""), "checkpoint_sha256": hashlib.sha256(open(ckpt, "rb").read()).hexdigest(),
            "run_date": datetime.date.today().isoformat(), "participants": n_participants, "sessions": n_sessions, "trials": n_trials,
            **{f"excluded_{r.rule}": int(r.n) for r in ledger.itertuples() if r.rule != "kept"},
            **{f"{r.level}s_kept": int(r.n) for r in ledger.itertuples() if r.rule == "kept"},
            **{k: (int(demographics[k]) if kind_of(k) in ("integer", "count") else float(demographics[k])) for k in DEMOGRAPHICS}}


def merge_numbers(analysis_dir: Path, extra: dict) -> dict:
    """Every stage's ``numbers.json`` plus ``extra`` (the provenance), checked against the manifest;
    duplicate keys are an error."""
    numbers = dict(extra)
    for stage in STAGES_WITH_NUMBERS:
        path = Path(analysis_dir) / stage / "numbers.json"
        if path.exists():
            for k, v in json.load(open(path)).items():
                if k in numbers:
                    raise ValueError(f"{k!r} is written by two stages")
                numbers[k] = v
    check_manifest(numbers)
    return numbers


def macros(numbers: dict) -> list:
    """(macro, key, formatted value) per number, plus a composed ``<stem>_CI`` ("est [lo, hi]") after each estimate/lo/hi triple."""
    rows = []
    for k, v in numbers.items():
        rows.append((macro_name(k), k, fmt(v, kind_of(k))))
        if k.endswith("_hi") and f"{k[:-3]}_estimate" in numbers and numbers[f"{k[:-3]}_estimate"] == numbers[f"{k[:-3]}_estimate"]:   # a NaN triple has no interval
            stem, kind = k[:-3], kind_of(f"{k[:-3]}_estimate")
            rows.append((macro_name(f"{stem}_CI"), f"{stem}_CI", f"{fmt(numbers[f'{stem}_estimate'], kind)} [{fmt(numbers[f'{stem}_lo'], kind)}, {fmt(v, kind)}]"))
    return rows


def tex(value: str, key: str) -> str:
    """Text-mode safe: in numbers, minus signs and '<' through ensuremath and the em dash as ---; text values only escape underscores."""
    if kind_of(key) != "text":
        value = value.replace("-", "\\ensuremath{-}").replace("<", "\\ensuremath{<}").replace("—", "---")
    return value.replace("_", "\\_")


def write_results(numbers: dict, out_dir: Path) -> list:
    """``results.tex`` and ``results.md`` under ``out_dir``; returns the two paths."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    rows, blocks = macros(numbers), {k: b for b, ks in MANIFEST.items() for k in ks}
    head = f"generated by src/analysis/report.py, commit {numbers['commit']}, {numbers['run_date']}; do not edit"
    (out_dir / "results.tex").write_text(f"% {head}\n" + "".join(f"\\newcommand{{\\{m}}}{{{tex(v, k)}}}\n" for m, k, v in rows))
    md = [f"<!-- {head} -->", ""]
    for block in MANIFEST:
        md += [f"## {block}", "", "| macro | key | value |", "|---|---|---|"] + [f"| `\\{m}` | `{k}` | {v} |" for m, k, v in rows if blocks.get(k.replace("_CI", "_hi"), None) == block] + [""]
    (out_dir / "results.md").write_text("\n".join(md))
    return [out_dir / "results.tex", out_dir / "results.md"]


def hypothesis_table(analysis_dir: Path) -> pd.DataFrame:
    """H1–H5 as the registration states them: estimate with its 95% CI, p, Holm p (confirmatory rows) and verdict; H4 is the
    partner-choice rate from its logistic model. Reward rows are reported without a rule."""
    c = pd.read_csv(Path(analysis_dir) / "descriptive" / "contrasts.csv").query("role != 'exploratory'").rename(columns={"lower.CL": "lo", "upper.CL": "hi", "p.value": "p"})
    h4 = pd.read_csv(Path(analysis_dir) / "partner_choice" / "model.csv").query("role == 'confirmatory'").iloc[0]
    ci = lambda est, lo, hi: f"{fmt(est, 'two')} [{fmt(lo, 'two')}, {fmt(hi, 'two')}]"
    rows = [dict(Hypothesis=r.hypothesis, Outcome=r.outcome, Estimate=ci(r.estimate, r.lo, r.hi), p=fmt(r.p, "pvalue"),
                 holm=fmt(r.p_holm, "pvalue") if r.role == "confirmatory" else "", Verdict=r.verdict if r.role == "confirmatory" else "reported") for r in c.itertuples()]
    rows.append(dict(Hypothesis="H4", Outcome="choice", Estimate=ci(h4.prob_estimate, h4.prob_lower, h4.prob_upper), p=fmt(h4["p.value"], "pvalue"), holm="", Verdict=h4.verdict))
    return pd.DataFrame(rows).sort_values("Hypothesis", kind="stable").rename(columns={"Estimate": "Estimate [95\\% CI]", "p": "$p$", "holm": "Holm $p$"})


def ladder_table(analysis_dir: Path) -> pd.DataFrame:
    """Every registry model: role, ELPD, difference from ROS with its SE, trials with Pareto k > 0.7."""
    lad = pd.read_csv(Path(analysis_dir) / "choice" / "ladder.csv", index_col=0)
    return pd.DataFrame([dict(Model=m, Role=REGISTRY[m].role or "", ELPD=fmt(lad.loc[m, "elpd"], "integer"),
                              delta="" if m == "ROS" else f"{fmt(lad.loc[m, 'delta'], 'integer')} ({fmt(lad.loc[m, 'se'], 'integer')})", bad_k=int(lad.loc[m, "n_bad_k"]))
                         for m in REGISTRY if m in lad.index]).rename(columns={"delta": "$\\Delta$ELPD (SE)", "bad_k": "$k > 0.7$"})


def write_tables(analysis_dir: Path, out_dir: Path) -> list:
    """``tables/hypotheses.tex`` and ``tables/ladder.tex`` under ``out_dir`` (booktabs, cells already formatted)."""
    out = Path(out_dir) / "tables"
    out.mkdir(parents=True, exist_ok=True)
    paths = []
    for name, table in (("hypotheses", hypothesis_table(analysis_dir)), ("ladder", ladder_table(analysis_dir))):
        cells = table.astype(str).map(lambda v: v.replace("-", "\\ensuremath{-}").replace("<", "\\ensuremath{<}") if v[:1].isdigit() or v[:1] == "-" or v[:1] == "<" else v)
        paths.append(out / f"{name}.tex")
        paths[-1].write_text(cells.style.hide(axis="index").to_latex(hrules=True, column_format="l" * 2 + "r" * (cells.shape[1] - 2)))
    return paths
